#!/usr/bin/env python3
"""Pack product photos into sprite sheets the page can show.

Each photo is trimmed of plain borders, centered on white in a 240x300 cell,
and packed 8x8 to a sheet (photos/sheet-NN.webp), most popular products first
so the top of the store loads only a few sheets. photos/index.js maps each
product name to its sheet and cell.

Official photos in official-photos/ (from scripts/kroger_api_photos.py) are used
first; Open Food Facts photos fill in where there is no official one.

Run:  python3 scripts/build_photo_sheets.py [cache_dir]
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageChops, ImageOps

ROOT = Path(__file__).resolve().parent.parent
CACHE = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / ".photo-cache")
OUT = ROOT / "photos"
CW, CH, COLS, ROWS = 240, 300, 8, 8
PAD = 10


def trim(im):
    """Cut away a plain border around the product, if the photo has one."""
    bg = Image.new(im.mode, im.size, im.getpixel((2, 2)))
    diff = ImageChops.difference(im, bg).convert("L").point(lambda v: 255 if v > 28 else 0)
    box = diff.getbbox()
    if box and (box[2] - box[0]) * (box[3] - box[1]) > 0.25 * im.width * im.height:
        im = im.crop(box)
    return im


def cell(path):
    im = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
    im = trim(im)
    im.thumbnail((CW - 2 * PAD, CH - 2 * PAD), Image.LANCZOS)
    c = Image.new("RGB", (CW, CH), "white")
    c.paste(im, ((CW - im.width) // 2, (CH - im.height) // 2))
    return c


def main():
    txt = (ROOT / "catalog.js").read_text()
    order = [r[0] for r in json.loads(txt[txt.index("{"):txt.rindex("}") + 1])["items"]]
    sources = json.loads((ROOT / "data" / "photo-sources.json").read_text())
    files = {}
    official = ROOT / "official-photos" / "found.csv"
    if official.exists():
        import csv
        for r in csv.DictReader(open(official)):
            path = ROOT / "official-photos" / r["file"]
            if path.exists():
                files[r["name"]] = ("k" + r["kroger_id"], path)
    for n, src in sources.items():
        if n not in files and src.get("front_score", 0) >= 2 and (CACHE / f"{src['code']}.jpg").exists():
            files[n] = (src["code"], CACHE / f"{src['code']}.jpg")
    names = [n for n in order if n in files]
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("sheet-*.webp"):
        old.unlink()
    index, per = {}, COLS * ROWS
    cells_by_code = {}
    sheet, slot, canvas = 0, 0, None
    for name in names:
        code, path = files[name]
        if code in cells_by_code:
            index[name] = cells_by_code[code]
            continue
        try:
            img = cell(path)
        except Exception as e:  # noqa: BLE001
            print("skip", name, e)
            continue
        if canvas is None:
            canvas = Image.new("RGB", (CW * COLS, CH * ROWS), "white")
        canvas.paste(img, ((slot % COLS) * CW, (slot // COLS) * CH))
        index[name] = cells_by_code[code] = [sheet, slot]
        slot += 1
        if slot == per:
            canvas.save(OUT / f"sheet-{sheet:02d}.webp", "WEBP", quality=72, method=6)
            sheet, slot, canvas = sheet + 1, 0, None
    if canvas is not None:
        canvas.save(OUT / f"sheet-{sheet:02d}.webp", "WEBP", quality=72, method=6)
        sheet += 1
    (OUT / "index.js").write_text(
        "/* Generated by scripts/build_photo_sheets.py. Photos: Open Food Facts contributors, CC BY-SA. */\n"
        "window.PHOTO_SHEETS=" + json.dumps({"cols": COLS, "rows": ROWS, "sheets": sheet, "items": index},
                                            separators=(",", ":"), ensure_ascii=False) + ";\n")
    size = sum(p.stat().st_size for p in OUT.glob("sheet-*.webp"))
    print(f"{len(index)} products with photos on {sheet} sheets, {size / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
